<?php

namespace App\Support\Authorization;

use App\Enums\Permission as P;
use App\Enums\Role;

/**
 * Single source of truth for which role holds which permission.
 * Seeded by RolesAndPermissionsSeeder and rendered to
 * docs/permissions-matrix.md by `php artisan affiliate:permissions-matrix`.
 */
final class PermissionMatrix
{
    /**
     * @return array<string, list<P>>
     */
    public static function definition(): array
    {
        return [
            Role::SuperAdmin->value => P::cases(),

            Role::AffiliateManager->value => [
                P::AdminAccess,
                P::AffiliatesView, P::AffiliatesReview, P::AffiliatesSuspend,
                P::CommissionRulesManage, P::CampaignsManage, P::MarketingAssetsManage,
                P::OrdersView, P::AttributionView, P::AttributionManual,
                P::CommissionsView, P::PayoutsView,
                P::ReportsView, P::FraudReview,
            ],

            Role::FinanceManager->value => [
                P::AdminAccess,
                P::AffiliatesView,
                P::OrdersView, P::AttributionView,
                P::CommissionsView, P::CommissionsAdjust,
                P::PayoutsView, P::PayoutsReview, P::PayoutsMarkPaid,
                P::ReconciliationView,
                P::ReportsView, P::ReportsExport,
            ],

            Role::Support->value => [
                P::AdminAccess,
                P::AffiliatesView,
                P::OrdersView, P::AttributionView,
            ],

            Role::Affiliate->value => [
                P::AffiliatePortal, P::AffiliatePayoutsRequest, P::CustomerPortal,
            ],

            Role::Customer->value => [
                P::CustomerPortal,
            ],
        ];
    }

    /**
     * @return list<string>
     */
    public static function permissionsFor(Role $role): array
    {
        return array_map(fn (P $p) => $p->value, self::definition()[$role->value]);
    }

    public static function toMarkdown(): string
    {
        $roles = Role::cases();
        $lines = [
            '# Permissions matrix',
            '',
            'Generated by `php artisan affiliate:permissions-matrix` from `app/Support/Authorization/PermissionMatrix.php`. Do not edit by hand.',
            '',
            'Every permission is enforced on the server (route middleware, policies or service checks). Hiding a button is never the control.',
            '',
            '| Permission | Description | '.implode(' | ', array_map(fn (Role $r) => $r->label(), $roles)).' |',
            '|---|---|'.str_repeat('---|', count($roles)),
        ];

        foreach (P::cases() as $permission) {
            $cells = array_map(
                fn (Role $r) => in_array($permission, self::definition()[$r->value], true) ? 'yes' : '',
                $roles,
            );
            $lines[] = '| `'.$permission->value.'` | '.$permission->description().' | '.implode(' | ', $cells).' |';
        }

        return implode("\n", $lines)."\n";
    }
}
